"""Embed a JS bundle as a C translation unit for the PS4 React host."""

from pathlib import Path
import sys

source = Path(sys.argv[1])
target = Path(sys.argv[2])
data = source.read_bytes()
with target.open("w", encoding="ascii", newline="\n") as out:
    out.write("/* Generated by tools/embed_bundle.py. */\n")
    out.write("const char app_bundle[] = {\n")
    for offset in range(0, len(data), 20):
        chunk = data[offset:offset + 20]
        out.write("  " + ",".join(str(byte) for byte in chunk) + ",\n")
    out.write("  0\n};\n")
    out.write(f"const unsigned long app_bundle_length = {len(data)};\n")
print(f"{target}: {len(data)} bytes")
